//==============================================================================
// 포함 모듈 목록.
//==============================================================================
const System = globalThis;
import { Object } from "./object.js";


//==============================================================================
// 딕셔너리.
//==============================================================================
/**
 * @template K, V
 * @class
 */
export class Dictionary extends Object {
	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================
	/** @private @type { Map<K, V> } */ #items;

	//==============================================================================
	// 생성.
	//==============================================================================
	/**
	 * @constructor
	 */
	constructor() {
		super();
		this.#items = new Map();
	}

	//==============================================================================
	// 전체 제거.
	//==============================================================================
	clear() {
		this.#items.length = 0;
	}

	//==============================================================================
	// 추가.
	//==============================================================================
	/**
	 * @param { K } key
	 * @param { V } value 
	 */
	add(key, value) {
		this.#items.set(key, value);
	}

	//==============================================================================
	// 제거.
	//==============================================================================
	/**
	 * @param { K } key
	 * @returns { boolean }
	 */
	remove(key) {
		return this.#items.delete(key);
	}

	/**
	 * @param { function(K, V): boolean } predicate
	 * @returns { { K, V } | undefined }
	 */
	find(predicate) {
		for (const [key, value] of this.#items) {
			if (predicate.call(key, value)) {
				return {
					key,
					value
				};
			}
		}
		return null;
	}

	/**
	 * @param { function(K, V): boolean } predicate
	 * @returns { { K, V }[] }
	 */
	findAll(predicate) {
		const items = [];
		for (const [key, value] of this.#items) {
			if (predicate.call(key, value)) {
				items.push({
					key,
					value
				});
			}
		}
		return items;
	}
	//==============================================================================
	// 요소가 포함되어있는지 여부 반환.
	//==============================================================================
	/**
	 * @returns { boolean } 
	 */
	contains(item) {
		return this.#items.has(item);
	}

	//==============================================================================
	// 요소 반환.
	//==============================================================================
	/**
	 * @param { K } key
	 * @returns { V } 
	 */
	get(key) {
		return this.#items.get(key);
	}

	//==============================================================================
	// 요소 수 반환.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getCount() {
		return this.#items.length;
	}

	//==============================================================================
	// 전체 요소 반환.
	//==============================================================================
	/**
	 * @returns { Map<K, V> } 
	 */
	getItems() {
		return this.#items;
	}

	//==============================================================================
	// 전체 키 반환.
	//==============================================================================
	/**
	 * @returns { K[] } 
	 */
	getKeys() {
		return Array.from(this.#items.keys());
	}

	//==============================================================================
	// 전체 값 반환.
	//==============================================================================
	/**
	 * @returns { V[] } 
	 */
	getKeys() {
		return Array.from(this.#items.values());
	}
}