//==============================================================================
// 포함 모듈 목록.
//==============================================================================
import * as VReflection from "./reflection.js";


//==============================================================================
// 기반 오브젝트.
//==============================================================================
/**
 * @class
 */
export class VObject {
	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================

	//==============================================================================
	// 생성.
	//==============================================================================
	/**
	 * @constant
	 */
	constructor() {

	}

	//==============================================================================
	// 비교.
	//==============================================================================
	/**
	 * @virtual
	 * @method
	 * @public
	 * @param { any } other
	 * @returns { boolean }
	 */
	equals(other) {
		if (other === null) {
			return false;
		}
		if (this === other) {
			return true;
		}

		return false;
	}

	//==============================================================================
	// 인스턴스 얕은 복제.
	//==============================================================================
	/**
	 * @method
	 * @public
	 * @returns { this }
	 */
	clone() {
		const obj = VReflection.clone(this);
		return obj;
	}

	//==============================================================================
	// 인스턴스 깊은 복제.
	//==============================================================================
	/**
	 * @method
	 * @public
	 * @returns { this }
	 */
	structuredClone() {
		const obj = VReflection.structuredClone(this);
		return obj;	
	}
}