//==============================================================================
// 포함 모듈 목록.
//==============================================================================
const System = globalThis;
import * as Reflection from "./reflection.js";


//==============================================================================
// 전역 상수 목록.
//==============================================================================
// 오브젝트마다의 고유식별자. (처음 getInstanceId() 를 부를 때 만들어 넣는다)
// 기반 오브젝트에 비공개 필드를 두면 Vector2, Rect, Color, TransformMatrix 처럼 프레임마다 많이 만드는 값 객체가 만들 때마다 그 칸을 채우므로 밖에 둔다.
const instanceIdTable = new System.WeakMap();


//==============================================================================
// 기반 오브젝트.
//==============================================================================
/**
 * @class
 */
export class Object {
	//==============================================================================
	// 생성.
	//==============================================================================
	/**
	 * @constant
	 */
	constructor() {
		// 고유식별자는 처음 부를 때 만든다. (Vector2, Rect, Color 처럼 많이 만드는 값 객체가 만들 때마다 GUID 를 짓지 않게)
	}

	//==============================================================================
	// 파괴. (현재 객체의 멤버 변수 목록을 무효화)
	//==============================================================================
	/**
	 * @virtual
	 */
	destroy() {
		const isDestroyed = this.isDestroyed();
		if (isDestroyed) {
			return;
		}

		// 처리.
	}

	//==============================================================================
	// 동등성 비교.
	//==============================================================================
	/**
	 * @virtual
	 * @param { any } other
	 * @returns { boolean }
	 */
	equals(other) {
		if (other === null) {
			return false;
		}
		else if (this === other) {
			return true;
		}

		return false;
	}

	//==============================================================================
	// 인스턴스 고유식별자 반환.
	//==============================================================================
	/**
	 * @virtual
	 * @returns { string }
	 */
	getInstanceId() {
		let instanceId = instanceIdTable.get(this);
		if (instanceId === undefined) {
			instanceId = Reflection.createGUID();
			instanceIdTable.set(this, instanceId);
		}
		return instanceId;
	}

	//==============================================================================
	// 파괴 여부 반환.
	// - destroy() 가 파괴 표시를 남기지 않으므로 늘 false 다.
	//==============================================================================
	/**
	 * @returns { boolean }
	 */
	isDestroyed() {
		return false;
	}

	//==============================================================================
	// 인스턴스 얕은 복제.
	//==============================================================================
	/**
	 * @returns { this }
	 */
	clone() {
		const obj = Reflection.clone(this);
		return obj;
	}

	//==============================================================================
	// 인스턴스 깊은 복제.
	//==============================================================================
	/**
	 * @returns { this }
	 */
	structuredClone() {
		const obj = Reflection.structuredClone(this);
		return obj;	
	}

	// //==============================================================================
	// // 새 인스턴스 생성.
	// //==============================================================================
	// /**
	//  * @static
	//  * @returns { this }
	//  */
	// static create() {
	// 	return new this();
	// }


	//==============================================================================
	// 유효한 객체인지 여부 반환.
	//==============================================================================
	/**
	 * @static
	 * @returns { boolean }
	 */
	static isValidate(target) {
		return Reflection.isValidate(target);
	}
}