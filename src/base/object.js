import * as VReflection from "./reflection.js";


//==============================================================================
// 기반 오브젝트.
//==============================================================================
export class VObject {
	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================

	//==============================================================================
	// 생성.
	//==============================================================================
	constructor() {

	}

	//==============================================================================
	// 인스턴스 얕은 복제.
	//==============================================================================
	/**
	 * @method
	 * @public
	 * @returns { this }
	 */
	clone() {
		const obj = VReflection.clone(this);
		return obj;
	}

	//==============================================================================
	// 인스턴스 깊은 복제.
	//==============================================================================
	/**
	 * @method
	 * @public
	 * @returns { this }
	 */
	structuredClone() {
		const obj = VReflection.structuredClone(this);
		return obj;	
	}
}