//==============================================================================
// 포함 모듈 목록.
//==============================================================================
const System = globalThis;
import * as Reflection from "./reflection.js";


//==============================================================================
// 기반 오브젝트.
//==============================================================================
/**
 * @class
 */
export class Object {
	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================
	/** @private @type { string } */ #instanceId; // 고유식별자. (처음 getInstanceId() 를 부를 때 만든다, 아직이면 빈 글)
	/** @private @type { boolean } */ #isDestroyed; // 고유식별자.

	//==============================================================================
	// 생성.
	//==============================================================================
	/**
	 * @constant
	 */
	constructor() {
		// 고유식별자는 처음 부를 때 만든다. (Vector2, Rect, Color 처럼 많이 만드는 값 객체가 만들 때마다 GUID 를 짓지 않게)
		this.#instanceId = "";
		this.#isDestroyed = false;
	}

	//==============================================================================
	// 파괴. (현재 객체의 멤버 변수 목록을 무효화)
	//==============================================================================
	/**
	 * @virtual
	 */
	destroy() {
		const isDestroyed = this.isDestroyed();
		if (isDestroyed) {
			return;
		}

		// 처리.
	}

	//==============================================================================
	// 동등성 비교.
	//==============================================================================
	/**
	 * @virtual
	 * @param { any } other
	 * @returns { boolean }
	 */
	equals(other) {
		if (other === null) {
			return false;
		}
		else if (this === other) {
			return true;
		}

		return false;
	}

	//==============================================================================
	// 인스턴스 고유식별자 반환.
	//==============================================================================
	/**
	 * @virtual
	 * @returns { string }
	 */
	getInstanceId() {
		if (this.#instanceId === "") {
			this.#instanceId = Reflection.createGUID();
		}
		return this.#instanceId;
	}

	//==============================================================================
	// 파괴 여부 반환.
	//==============================================================================
	/**
	 * @returns { boolean }
	 */
	isDestroyed() {
		return this.#isDestroyed;
	}

	//==============================================================================
	// 인스턴스 얕은 복제.
	//==============================================================================
	/**
	 * @returns { this }
	 */
	clone() {
		const obj = Reflection.clone(this);
		return obj;
	}

	//==============================================================================
	// 인스턴스 깊은 복제.
	//==============================================================================
	/**
	 * @returns { this }
	 */
	structuredClone() {
		const obj = Reflection.structuredClone(this);
		return obj;	
	}

	// //==============================================================================
	// // 새 인스턴스 생성.
	// //==============================================================================
	// /**
	//  * @static
	//  * @returns { this }
	//  */
	// static create() {
	// 	return new this();
	// }


	//==============================================================================
	// 유효한 객체인지 여부 반환.
	//==============================================================================
	/**
	 * @static
	 * @returns { boolean }
	 */
	static isValidate(target) {
		return Reflection.isValidate(target);
	}
}