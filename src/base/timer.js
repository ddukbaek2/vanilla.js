//==============================================================================
// 포함 모듈 목록.
//==============================================================================
const System = globalThis;
import { Object } from "./object.js";


//==============================================================================
// 쿨다운.
// - "timer -= dt; if (timer <= 0) ..." 를 매번 손으로 쓰던 것을 표준화했다.
// - use() 로 발동하면 지정한 시간 동안 isReady() 가 거짓이 된다.
//==============================================================================
export class Cooldown extends Object {
	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================
	/** @private @type { number } */ #duration;
	/** @private @type { number } */ #remainSeconds;

	//==============================================================================
	// 생성.
	//==============================================================================
	/**
	 * @constructor
	 * @param { number } duration 쿨다운 시간. (초)
	 */
	constructor(duration = 1) {
		super();

		this.#duration = System.Math.max(0, duration);
		this.#remainSeconds = 0;
	}

	//==============================================================================
	// 갱신.
	//==============================================================================
	/**
	 * @param { number } timeDelta
	 */
	tick(timeDelta) {
		if (this.#remainSeconds > 0) {
			this.#remainSeconds = System.Math.max(0, this.#remainSeconds - timeDelta);
		}
	}

	//==============================================================================
	// 발동 가능 여부.
	//==============================================================================
	/**
	 * @returns { boolean }
	 */
	isReady() {
		return this.#remainSeconds <= 0;
	}

	//==============================================================================
	// 발동. (준비되어 있으면 쿨다운을 시작하고 참을 반환)
	//==============================================================================
	/**
	 * @returns { boolean }
	 */
	use() {
		if (!this.isReady()) {
			return false;
		}
		this.#remainSeconds = this.#duration;
		return true;
	}

	//==============================================================================
	// 곧바로 준비 상태로 되돌리기.
	//==============================================================================
	reset() {
		this.#remainSeconds = 0;
	}

	//==============================================================================
	// 쿨다운 시간 설정.
	//==============================================================================
	/**
	 * @param { number } duration
	 */
	setDuration(duration) {
		this.#duration = System.Math.max(0, duration);
	}

	//==============================================================================
	// 쿨다운 시간 반환.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getDuration() {
		return this.#duration;
	}

	//==============================================================================
	// 남은 시간 반환.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getRemainSeconds() {
		return this.#remainSeconds;
	}

	//==============================================================================
	// 진행 비율 반환. (0 = 방금 발동, 1 = 준비 완료)
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getProgress() {
		if (this.#duration <= 0) {
			return 1;
		}
		return 1 - this.#remainSeconds / this.#duration;
	}
}


//==============================================================================
// 반복 타이머.
// - 일정 간격마다 콜백을 부른다. 프레임이 길어져 여러 번 지나쳤으면 밀린 만큼 몰아서 부른다.
//==============================================================================
export class RepeatTimer extends Object {
	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================
	/** @private @type { number } */ #interval;
	/** @private @type { number } */ #elapsedSeconds;
	/** @private @type { Function | null } */ #elapsedEvent;
	/** @private @type { boolean } */ #isRunning;

	//==============================================================================
	// 생성.
	//==============================================================================
	/**
	 * @constructor
	 * @param { number } interval 간격. (초)
	 * @param { Function } elapsedEvent 간격마다 부르는 콜백.
	 */
	constructor(interval = 1, elapsedEvent = null) {
		super();

		this.#interval = System.Math.max(0.000001, interval);
		this.#elapsedSeconds = 0;
		this.#elapsedEvent = elapsedEvent;
		this.#isRunning = true;
	}

	//==============================================================================
	// 갱신.
	//==============================================================================
	/**
	 * @param { number } timeDelta
	 */
	tick(timeDelta) {
		if (!this.#isRunning) {
			return;
		}
		this.#elapsedSeconds += timeDelta;
		while (this.#elapsedSeconds >= this.#interval) {
			this.#elapsedSeconds -= this.#interval;
			if (this.#elapsedEvent) {
				this.#elapsedEvent();
			}
		}
	}

	//==============================================================================
	// 시작.
	//==============================================================================
	start() {
		this.#isRunning = true;
	}

	//==============================================================================
	// 정지. (누적 시간도 비운다)
	//==============================================================================
	stop() {
		this.#isRunning = false;
		this.#elapsedSeconds = 0;
	}

	//==============================================================================
	// 일시 정지.
	//==============================================================================
	pause() {
		this.#isRunning = false;
	}

	//==============================================================================
	// 간격 설정.
	//==============================================================================
	/**
	 * @param { number } interval
	 */
	setInterval(interval) {
		this.#interval = System.Math.max(0.000001, interval);
	}

	//==============================================================================
	// 간격 반환.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getInterval() {
		return this.#interval;
	}

	//==============================================================================
	// 콜백 설정.
	//==============================================================================
	/**
	 * @param { Function } elapsedEvent
	 */
	setElapsedEvent(elapsedEvent) {
		this.#elapsedEvent = elapsedEvent;
	}

	//==============================================================================
	// 동작 중 여부.
	//==============================================================================
	/**
	 * @returns { boolean }
	 */
	isRunning() {
		return this.#isRunning;
	}
}
