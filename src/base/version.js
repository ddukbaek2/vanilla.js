//==============================================================================
// 포함 모듈 목록.
//==============================================================================
export const System = globalThis;
export { Object } from "./object.js";


//==============================================================================
// 버전 클래스.
//==============================================================================
export class Version extends Object {
	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================
	/** @private @type { number } */ #major;
	/** @private @type { number } */ #minor;
	/** @private @type { number } */ #patch;
	/** @private @type { string } */ #branch;

	//==============================================================================
	// 생성.
	//==============================================================================
	/**
	 * @constructor
	 */
	constructor() {
		super();
		this.#major = 0;
		this.#minor = 0;
		this.#patch = 0;
		this.#branch = "";
	}

	//==============================================================================
	// 메이저 설정.
	//==============================================================================
	/**
	 * @param { number } major
	 */
	setMajor(major) {
		this.#major = major;
	}

	//==============================================================================
	// 메이저 반환.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getMajor() {
		return this.#major;
	}
	
	//==============================================================================
	// 마이너 설정.
	//==============================================================================
	/**
	 * @param { number } minor
	 */
	setMinor(minor) {
		this.#minor = minor;
	}

	//==============================================================================
	// 마이너 반환.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getMinor() {
		return this.#minor;
	}

	//==============================================================================
	// 패치 설정.
	//==============================================================================
	/**
	 * @param { number } patch
	 */
	setPatch(patch) {
		this.#patch = patch;
	}

	//==============================================================================
	// 패치 반환.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getPatch() {
		return this.#patch;
	}

	//==============================================================================
	// 브랜치 설정.
	//==============================================================================
	/**
	 * @param { string } branch
	 */
	setBranch(branch) {
		this.#branch = branch;
	}

	//==============================================================================
	// 브랜치 반환.
	//==============================================================================
	/**
	 * @returns { string }
	 */
	getBranch() {
		return this.#branch;
	}

	//==============================================================================
	// 버전 문자열 반환.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getVersionString() {
		const major = this.getMajor();
		const minor = this.getMinor();
		const patch = this.getPatch();
		const branch = this.getBranch();

		if (branch === "") {
			return `${major}.${minor}.${patch}`;
		}
		else {
			return `${major}.${minor}.${patch}-${branch}`;
		}
	}

	//==============================================================================
	// 생성.
	//==============================================================================
	/**
	 * @param { number } major 
	 * @param { number } minor
	 * @param { number } patch
	 * @param { string } branch
	 */
	static create(major, minor, patch, branch = "") {
		const version = new Version();
		version.setMajor(major);
		version.setMinor(minor);
		version.setPatch(patch);
		version.setBranch(branch);
		return version;
	}
}