//==============================================================================
// 포함 모듈 목록.
//==============================================================================
const System = globalThis;
import { Object } from "./object.js";


//==============================================================================
// 버전 클래스.
//==============================================================================
/**
 * @example <caption>버전 문자열 만들기</caption>
 * import { Version } from "./build/vanilla.js";
 *
 * const version = Version.create(0, 4, 0, "dev");
 * console.log(version.getVersionString());
 *
 * version.setBranch("");
 * version.setPatch(1);
 * console.log(version.getVersionString(), version.getMajor(), version.getMinor());
 */
export class Version extends Object {
	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================
	/** @private @type { number } */ #major;
	/** @private @type { number } */ #minor;
	/** @private @type { number } */ #patch;
	/** @private @type { string } */ #branch;

	//==============================================================================
	// 생성.
	//==============================================================================
	/**
	 * @constructor
	 */
	constructor() {
		super();
		this.#major = 0;
		this.#minor = 0;
		this.#patch = 0;
		this.#branch = "";
	}

	//==============================================================================
	// 메이저 설정.
	//==============================================================================
	/**
	 * @param { number } major 메이저 번호.
	 */
	setMajor(major) {
		this.#major = major;
	}

	//==============================================================================
	// 메이저 반환.
	//==============================================================================
	/**
	 * @returns { number } 메이저 번호.
	 */
	getMajor() {
		return this.#major;
	}
	
	//==============================================================================
	// 마이너 설정.
	//==============================================================================
	/**
	 * @param { number } minor 마이너 번호.
	 */
	setMinor(minor) {
		this.#minor = minor;
	}

	//==============================================================================
	// 마이너 반환.
	//==============================================================================
	/**
	 * @returns { number } 마이너 번호.
	 */
	getMinor() {
		return this.#minor;
	}

	//==============================================================================
	// 패치 설정.
	//==============================================================================
	/**
	 * @param { number } patch 패치 번호.
	 */
	setPatch(patch) {
		this.#patch = patch;
	}

	//==============================================================================
	// 패치 반환.
	//==============================================================================
	/**
	 * @returns { number } 패치 번호.
	 */
	getPatch() {
		return this.#patch;
	}

	//==============================================================================
	// 브랜치 설정.
	//==============================================================================
	/**
	 * @param { string } branch 브랜치 이름. (빈 글이면 버전 문자열에 붙이지 않는다)
	 */
	setBranch(branch) {
		this.#branch = branch;
	}

	//==============================================================================
	// 브랜치 반환.
	//==============================================================================
	/**
	 * @returns { string } 브랜치 이름. (없으면 빈 글)
	 */
	getBranch() {
		return this.#branch;
	}

	//==============================================================================
	// 버전 문자열 반환.
	//==============================================================================
	/**
	 * @returns { number } "major.minor.patch" 꼴 문자열. (브랜치가 있으면 "-branch" 를 붙인다)
	 */
	getVersionString() {
		const major = this.getMajor();
		const minor = this.getMinor();
		const patch = this.getPatch();
		const branch = this.getBranch();

		if (branch === "") {
			return `${major}.${minor}.${patch}`;
		}
		else {
			return `${major}.${minor}.${patch}-${branch}`;
		}
	}

	//==============================================================================
	// 생성.
	//==============================================================================
	/**
	 * @param { number } major 메이저 번호.
	 * @param { number } minor 마이너 번호.
	 * @param { number } patch 패치 번호.
	 * @param { string } branch 브랜치 이름. (기본 빈 글)
	 * @returns { Version } 만든 버전.
	 */
	static create(major, minor, patch, branch = "") {
		const version = new Version();
		version.setMajor(major);
		version.setMinor(minor);
		version.setPatch(patch);
		version.setBranch(branch);
		return version;
	}
}