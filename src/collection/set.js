//==============================================================================
// 포함 모듈 목록.
//==============================================================================
const System = globalThis;
import { Object } from "../object.js";


//==============================================================================
// 셋 (중복 불허 집합).
//==============================================================================
/**
 * @template T
 * @class
 */
export class Set extends Object {
	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================
	/** @private @type { Set<T> } */ #items;

	//==============================================================================
	// 생성.
	//==============================================================================
	/**
	 * @constructor
	 */
	constructor() {
		super();
		this.#items = new System.Set();
	}

	//==============================================================================
	// 데이터 추가.
	//==============================================================================
	/**
	 * @param { T } item 
	 */
	add(item) {
		this.#items.add(item);
	}

	//==============================================================================
	// 데이터 제거.
	//==============================================================================
	/**
	 * @param { T } item 
	 * @returns { boolean }
	 */
	remove(item) {
		return this.#items.delete(item);
	}

	//==============================================================================
	// 요소 포함 여부 반환.
	//==============================================================================
	/**
	 * @param { T } item 
	 * @returns { boolean }
	 */
	contains(item) {
		return this.#items.has(item);
	}

	//==============================================================================
	// 전체 제거.
	//==============================================================================
	clear() {
		this.#items.clear();
	}

	//==============================================================================
	// 요소 수 반환.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getCount() {
		return this.#items.size;
	}

	//==============================================================================
	// 전체 요소 배열 반환.
	//==============================================================================
	/**
	 * @returns { T[] }
	 */
	toArray() {
		return Array.from(this.#items);
	}
}