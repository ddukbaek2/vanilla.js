//==============================================================================
// 포함 모듈 목록.
//==============================================================================
const System = globalThis;
import * as Math from "../base/math.js";
import { Object } from "../base/object.js";
import { Vector2 } from "../base/vector2.js";


//==============================================================================
// 카메라 클래스.
//==============================================================================
/**
 * 게임 월드를 비추는 카메라 클래스입니다.
 * 위치, 줌, 회전 기능을 제공하며 렌더링 컨텍스트에 변환을 적용합니다.
 */
export class Camera extends Object {
	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================
	/** @private @type { Vector2 } */ #position; // 카메라가 바라보는 중심 위치.
	/** @private @type { number } */ #zoom; // 확대/축소 비율.
	/** @private @type { number } */ #rotation; // 회전 각도 (라디안).

	//==============================================================================
	// 생성.
	//==============================================================================
	constructor() {
		super();
		this.#position = Vector2.zero();
		this.#zoom = 1.0;
		this.#rotation = 0;
	}

	//==============================================================================
	// 시작.
	//==============================================================================
	/**
	 * @param { CanvasRenderingContext2D } canvasContext 
	 */
	begin(canvasContext) {
		if (canvasContext) {
			const zoom = this.getZoom();
			const rotation = this.getRotation();
			const radian = Math.degreeToRadian(rotation);

			canvasContext.save();
			// canvasContext.translate(viewportSize.x / 2, viewportSize.y / 2);
			canvasContext.scale(zoom, zoom);
			canvasContext.rotate(radian);
			canvasContext.translate(-this.#position.x, -this.#position.y);
		}
	}

	//==============================================================================
	// 종료.
	//==============================================================================
	/**
	 * @param { CanvasRenderingContext2D } canvasContext 
	 */
	end(canvasContext) {
		if (canvasContext) {
			canvasContext.restore();
		}
	}

	//==============================================================================
	// 이동 설정.
	//==============================================================================
	/**
	 * @param { Vector2 } position
	 */
	setPosition(position) {
		this.#position = position;
	}

	//==============================================================================
	// 이동 반환.
	//==============================================================================
	/**
	 * @returns { Vector2 }
	 */
	getPosition() {
		return this.#position;
	}

	//==============================================================================
	// 줌 설정.
	//==============================================================================
	/**
	 * @param { number } zoom 
	 */
	setZoom(zoom) {
		this.#zoom = Math.clamp(0.001, zoom);
	}

	//==============================================================================
	// 줌 반환.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getZoom() {
		return this.#zoom;
	}

	//==============================================================================
	// 회전 설정.
	//==============================================================================
	/**
	 * @param { number } rotation 
	 */
	setRotation(rotation) {
		this.#rotation = rotation;
	}

	//==============================================================================
	// 회전 반환.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getRotation() {
		return this.#rotation;
	}
}