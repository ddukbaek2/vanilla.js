	// - tick 을 다시 정의했어도 할 일이 없는 때가 있으면 하위 클래스가 다시 정의한다.
	//==============================================================================
	/**
	 * @virtual
	 * @returns { boolean }
	 */
	isTickNeeded() {
		return this.tick !== Component.prototype.tick;
	}

