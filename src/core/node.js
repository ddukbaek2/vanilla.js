//==============================================================================
// 포함 모듈 목록.
//==============================================================================
import { VObject } from "../base/object.js";
import { VVector2 } from "../base/vector2.js";
import { VRenderer } from "./renderer.js";


//==============================================================================
// 영역 및 계층 객체.
//==============================================================================
/**
 * @class
 */
export class VNode extends VObject {
	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================
	/** @type { VNode } */ #parent;
	/** @type { VNode[] } */ #children;
	/** @type { VVector2 } */ #position;
	/** @type { VVector2 } */ #size;
	/** @type { number } */ #rotation;
	/** @type { boolean } */ #isVisible;

	//==============================================================================
	// 생성.
	//==============================================================================
	/**
	 * @constructor
	 */
	constructor() {
		super();
		this.#parent = null;
		this.#children = [];
		this.#position = VVector2.zero();
		this.#size = VVector2.zero();
		this.#rotation = 0.0;
		this.#isVisible = true;
	}

	//==============================================================================
	// 갱신.
	//==============================================================================
	/**
	 * @virtual
	 * @param { number } timeDelta 
	 */
	update(timeDelta) {

	}

	//==============================================================================
	// 이전 출력.
	//==============================================================================
	/**
	 * @virtual
	 * @param { VRenderer } renderer 
	 */
	preDraw(renderer) {

	}

	//==============================================================================
	// 출력.
	//==============================================================================
	/**
	 * @virtual
	 * @param { VRenderer } renderer 
	 */
	draw(renderer) {
		// renderer.canvasContext.draw()
	}

	//==============================================================================
	// 이후 출력.
	//==============================================================================
	/**
	 * @virtual
	 * @param { VRenderer } renderer 
	 */
	postDraw(renderer) {

	}

	//==============================================================================
	// 부모 설정.
	//==============================================================================
	/**
	 * @param { VNode } parent 
	 */
	setParent(parent) {
		// 기존 부모가 존재 할 경우.
		if (this.#parent) {
			// 동일 부모.
			if (this.#parent === parent) {
				return;
			}

			// 자식 제거.
			const index = this.#parent.#children.indexOf(this);
			if (index !== -1) {
				this.#parent.#children.splice(index, 1);
			}

			this.#parent = null;
		}

		this.#parent = parent;

		// 새 부모가 존재 할 경우.
		if (this.#parent) {

			// 자식 추가.
			parent.#children.push(this);
		}
	}

	//==============================================================================
	// 부모 반환.
	//==============================================================================
	/**
	 * @returns { VNode } 
	 */
	getParent() {
		return this.#parent;
	}

	//==============================================================================
	// 자식 목록 반환.
	//==============================================================================
	/**
	 * @returns { VNode[] } 
	 */
	getChildren() {
		return this.#children;
	}

	//==============================================================================
	// 자식 수 반환.
	//==============================================================================
	/**
	 * @returns { number } 
	 */
	getChildCount(index) {
		return this.#children.length;
	}

	//==============================================================================
	// 자식 반환.
	//==============================================================================
	/**
	 * @returns { VNode } 
	 */
	getChild(index) {
		return this.#children[index];
	}

	//==============================================================================
	// 위치 설정.
	//==============================================================================
	/**
	 * @param { VVector2 } position 
	 */
	setPosition(position) {
		this.#position = position;
	}

	//==============================================================================
	// 위치 반환.
	//==============================================================================
	/**
	 * @returns { VVector2 } 
	 */
	getPosition() {
		return this.#position;
	}

	//==============================================================================
	// 크기 설정.
	//==============================================================================
	/**
	 * @param { VVector2 } size 
	 */
	setSize(size) {
		this.#size = size;
	}

	//==============================================================================
	// 크기 반환.
	//==============================================================================
	/**
	 * @returns { VVector2 } 
	 */
	getSize() {
		return this.#size;
	}

	//==============================================================================
	// 회전 설정.
	//==============================================================================
	/**
	 * @param { number } rotation 
	 */
	setRotation(rotation) {
		this.#rotation = rotation;
	}

	//==============================================================================
	// 회전 반환.
	//==============================================================================
	/**
	 * @returns { number } 
	 */
	getRotation() {
		return this.#rotation;
	}

	//==============================================================================
	// 가시 상태 설정.
	//==============================================================================
	/**
	 * @param { boolean } visible 
	 */
	setVisible(visible) {
		this.#isVisible = visible;
	}

	//==============================================================================
	// 가시 상태 반환.
	//==============================================================================
	/**
	 * @returns { boolean } 
	 */
	isVisible() {
		return this.#isVisible;
	}

	//==============================================================================
	// 새로운 노드 생성.
	//==============================================================================
	/**
	 * @returns { VNode }
	 */
	static create() {
		var obj = new VNode();
		return obj;
	}
}