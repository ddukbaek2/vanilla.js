//==============================================================================
// 포함 모듈 목록.
//==============================================================================
import { VObject } from "../base/object.js";
import { VEngine } from "./engine.js";
import { VRenderer } from "./renderer.js";
import { VNode } from "./node.js";


//==============================================================================
// 씬.
//==============================================================================
export class VScene extends VObject {
	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================
	/** @private @type { VEngine } */ #engine;
	/** @private @type { VNode } */ #root;

	//==============================================================================
	// 생성.
	//==============================================================================
	constructor() {
		super();
		this.#root = new VNode();
		this.create();
	}
	
	//==============================================================================
	// 생성.
	//==============================================================================
	/**
	 * @virtual
	 */
	create() {
	}

	//==============================================================================
	// 초기화.
	//==============================================================================
	/**
	 * @virtual
	 * @param { VEngine } engine 
	 */
	initialize(engine) {
		this.#engine = engine;
	}

	//==============================================================================
	// 파괴.
	//==============================================================================
	/**
	 * @virtual
	 */
	finalize() {

	}

	//==============================================================================
	// 비동기 로딩.
	//==============================================================================
	/**
	 * @virtual
	 * @param { VEngine } engine 
	 */
	async load(engine) {
		await Promise.resolve();
	}

	//==============================================================================
	// 비동기 로딩 해제.
	//==============================================================================
	/**
	 * @virtual
	 * @param { VEngine } engine 
	 */
	async unload(engine) {
		await Promise.resolve();
	}

	//==============================================================================
	// 주기적 갱신.
	//==============================================================================
	/**
	 * @virtual
	 * @param { number } timeDelta 
	 */
	tick(timeDelta) {
		this.#root.tick(timeDelta);
	}

	//==============================================================================
	// 출력.
	//==============================================================================
	/**
	 * @virtual
	 * @param { VRenderer } renderer 
	 */
	draw(renderer) {
		renderer.drawNode(this.#root);
	}

	//==============================================================================
	// 엔진 반환.
	//==============================================================================
	/**
	 * @returns { VEngine } 
	 */
	getEngine() {
		return this.#engine;
	}
	
	//==============================================================================
	// 루트 노드 반환.
	//==============================================================================
	/**
	 * @returns { VRenderer } 
	 */
	getRoot() {
		return this.#root;
	}
}