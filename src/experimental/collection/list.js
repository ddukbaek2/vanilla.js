//==============================================================================
// 포함 모듈 목록.
//==============================================================================
const System = globalThis;
import { Object } from "../../base/object.js";


//==============================================================================
// 리스트.
//==============================================================================
/**
 * @template T
 * @class
 */
export class List extends Object {
	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================
	/** @private @type { T[] } */ #items;

	//==============================================================================
	// 생성.
	//==============================================================================
	/**
	 * @constructor
	 */
	constructor() {
		super();
		this.#items = [];
	}

	//==============================================================================
	// 전체 제거.
	//==============================================================================
	clear() {
		this.#items.length = 0;
	}

	//==============================================================================
	// 추가.
	//==============================================================================
	/**
	 * @param { T } item 
	 */
	add(item) {
		this.#items.push(item);
	}

	//==============================================================================
	// 범위 추가.
	//==============================================================================
	/**
	 * @param { T[] } items
	 */
	addRange(items) {
		for (const item of items) {
			this.#items.push(item);
		}
	}

	//==============================================================================
	// 제거.
	//==============================================================================
	/**
	 * @param { T } item
	 * @returns { boolean }
	 */
	remove(item) {
		const index = this.#items.indexOf(item);
		if (index !== -1) {
			this.#items.splice(index, 1);
			return true;
		}

		return false;
	}

	//==============================================================================
	// 제거.
	//==============================================================================
	/**
	 * @param { number } index
	 * @returns { boolean }
	 */
	removeAt(index) {
		if (index < 0 || index >= this.#items.length) {
			return false;
		}

		this.#items.splice(index, 1);
		return true;
	}

	//==============================================================================
	// 요소 검색.
	//==============================================================================
	/**
	 * @param { function(number, T): boolean } predicate
	 * @returns { T | undefined }
	 */
	find(predicate) {
		let index = 0;
		const items = this.all();
		for (const item of items) {
			if (predicate.call(index, item)) {
				return item;
			}
			++index;
		}
		return undefined;
	}

	//==============================================================================
	// 요소 검색.
	//==============================================================================
	/**
	 * @param { function(number, T): boolean } predicate
	 * @returns { T[] }
	 */
	findAll(predicate) {
		let index = 0;
		const result = [];
		const allItems = this.all();
		for (const item of allItems) {
			if (predicate.call(index, item)) {
				result.push(item);
			}
			++index;
		}
		return result;
	}
	
	//==============================================================================
	// 요소가 포함되어있는지 여부 반환.
	//==============================================================================
	/**
	 * @returns { boolean } 
	 */
	contains(item) {
		return this.#items.includes(item);
	}

	//==============================================================================
	// 색인 반환.
	//==============================================================================
	/**
	 * @returns { number } 
	 */
	indexOf(item) {
		return this.#items.indexOf(item);
	}

	//==============================================================================
	// 요소 반환.
	//==============================================================================
	/**
	 * @returns { T } 
	 */
	getAt(index) {
		return this.#items[index];
	}

	//==============================================================================
	// 리스트가 비어있는지 여부 반환.
	//==============================================================================
	/**
	 * @returns { boolean } 
	 */
	isEmpty() {
		return this.#items.length === 0;
	}

	//==============================================================================
	// 리스트 요소 수 반환.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getCount() {
		return this.#items.length;
	}

	//==============================================================================
	// 전체 요소 반환.
	//==============================================================================
	/**
	 * @returns { T[] } 
	 */
	all() {
		return this.#items;
	}
}