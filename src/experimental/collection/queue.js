//==============================================================================
// 포함 모듈 목록.
//==============================================================================
const System = globalThis;
import { Object } from "../../base/object.js";


//==============================================================================
// 큐 (FIFO).
//==============================================================================
/**
 * @template T
 * @class
 */
export class Queue extends Object {
	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================
	/** @private @type { T[] } */ #items;

	//==============================================================================
	// 생성.
	//==============================================================================
	/**
	 * @constructor
	 */
	constructor() {
		super();
		this.#items = [];
	}

	//==============================================================================
	// 데이터 추가.
	//==============================================================================
	/**
	 * @param { T } item 
	 */
	enqueue(item) {
		this.#items.push(item);
	}

	//==============================================================================
	// 데이터 추출 및 제거.
	//==============================================================================
	/**
	 * @returns { T | undefined }
	 */
	dequeue() {
		return this.#items.shift();
	}

	//==============================================================================
	// 데이터 확인 (제거하지 않음).
	//==============================================================================
	/**
	 * @returns { T | undefined }
	 */
	peek() {
		return this.#items[0];
	}

	//==============================================================================
	// 전체 제거.
	//==============================================================================
	clear() {
		this.#items.length = 0;
	}

	//==============================================================================
	// 비어있는지 여부 반환.
	//==============================================================================
	/**
	 * @returns { boolean }
	 */
	isEmpty() {
		return this.#items.length === 0;
	}

	//==============================================================================
	// 요소 수 반환.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getCount() {
		return this.#items.length;
	}

	//==============================================================================
	// 전체 요소 배열 반환.
	//==============================================================================
	/**
	 * @returns { T[] }
	 */
	toArray() {
		return [...this.#items];
	}
}