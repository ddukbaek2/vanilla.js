import { VVector2 } from "../base/vector2.js";
import { VRenderer } from "../core/renderer.js"
import { VSprite } from "./sprite.js";


//==============================================================================
// 스프라이트.
//==============================================================================
export class VAnimatedSprite extends VSprite {
	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================
	/** @type { VVector2 } */ position = null;

	//==============================================================================
	// 생성.
	//==============================================================================
	constructor() {
		super();
		
		this.position = VVector2.zero();
	}

	//==============================================================================
	// 갱신.
	//==============================================================================
	/**
	 * @override
	 * @param { number } timeDelta 
	 */
	update(timeDelta) {
		super.update(timeDelta);
	}

	//==============================================================================
	// 출력.
	//==============================================================================
	/**
	 * @override
	 * @param { VRenderer } renderer 
	 */
	draw(renderer) {
		super.draw(renderer);
	}
}