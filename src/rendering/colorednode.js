//==============================================================================
// 포함 모듈 목록.
//==============================================================================
import { VVector2 } from "../base/vector2.js";
import { VNode } from "../core/node.js";
import { VRenderer } from "../core/renderer.js";


//==============================================================================
// 색상 출력 객체.
//==============================================================================
export class VColoredNode extends VNode {
	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================
	/** @type { string } */ #color;
	/** @type { number } */ #opacity;

	//==============================================================================
	// 생성.
	//==============================================================================
	/**
	 * @constructor
	 */
	constructor() {
		super();
		this.#color = "#ffffff"; // rgba(255, 255, 255, 1.0);
		this.#opacity = 0.0;
	}

	//==============================================================================
	// 갱신.
	//==============================================================================
	/**
	 * @override
	 * @param { number } timeDelta 
	 */
	update(timeDelta) {
		super.update(timeDelta);
	}

	//==============================================================================
	// 이전 출력.
	//==============================================================================
	/**
	 * @override
	 * @param { VRenderer } renderer 
	 */
	preDraw(renderer) {
		super.preDraw(renderer);
	}

	//==============================================================================
	// 출력.
	//==============================================================================
	/**
	 * @override
	 * @param { VRenderer } renderer 
	 */
	draw(renderer) {
		super.draw(renderer);
	}

	//==============================================================================
	// 이후 출력.
	//==============================================================================
	/**
	 * @override
	 * @param { VRenderer } renderer 
	 */
	postDraw(renderer) {
		super.draw(renderer);
	}

	//==============================================================================
	// 투명도 설정.
	//==============================================================================
	/**
	 * @param { number } opacity 
	 */
	setOpacity(opacity) {
		this.#opacity = opacity;
	}

	//==============================================================================
	// 투명도 반환.
	//==============================================================================
	/**
	 * @returns { number } 
	 */
	getOpacity() {
		return this.#opacity;
	}

	//==============================================================================
	// 새로운 색상 노드 생성.
	//==============================================================================
	/**
	 * @returns { VColoredNode }
	 */
	static create() {
		var obj = new VColoredNode();
		return obj;
	}
}