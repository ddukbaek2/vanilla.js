//==============================================================================
// 포함 모듈 목록.
//==============================================================================
const System = globalThis;
import { Object } from "../base/object.js";
import { Frame } from "../core/frame.js";



//==============================================================================
// 애니메이션 클립.
//==============================================================================
export class AnimationClip extends Object {
	/** @private @type { Frame[] } */ #frames; // 프레임 목록.
	/** @private @type { boolean } */ #isLoop; // 반복 재생 여부.
	/** @private @type { number } */ #duration; // 총 애니메이션 재생 시간.

	//==============================================================================
	// 생성.
	//==============================================================================
	/**
	 * @constructor
	 */
	constructor() {
		super();
		this.#frames = [];
		this.#duration = 0;
		this.#isLoop = false;
	}

	//==============================================================================
	// 프레임 목록 설정.
	//==============================================================================
	/**
	 * @param { Frame[] } frames
	 */
	setFrames(frames) {
		this.#frames = frames;
	}

	//==============================================================================
	// 반복 재생 여부 설정.
	//==============================================================================
	/**
	 * @param { boolean } isLoop
	 */
	setLoop(isLoop) {
		this.#isLoop = isLoop;
	}

	//==============================================================================
	// 애니메이션 지속 시간 설정.
	//==============================================================================
	/**
	 * @param { number } duration
	 */
	setDuration(duration) {
		this.#duration = duration;
	}

	//==============================================================================
	// 반복 재생 여부 반환.
	//==============================================================================
	/**
	 * @returns { boolean }
	 */
	isLoop() {
		return this.#isLoop;
	}

	//==============================================================================
	// 대상 인덱스에 대한 프레임 반환.
	//==============================================================================
	/**
	 * @param { number } index
	 * @returns { Frame }
	 */
	getFrame(index) {
		return this.#frames[index];
	}

	//==============================================================================
	// 프레임 목록 반환.
	//==============================================================================
	/**
	 * @returns { Frame[] }
	 */
	getFrames() {
		return this.#frames;
	}

	//==============================================================================
	// 전체 프레임 수 반환.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getFrameCount() {
		return this.#frames.length;
	}

	//==============================================================================
	// 애니메이션 지속 시간 반환.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getDuration() {
		return this.#duration;
	}
}