//==============================================================================
// 포함 모듈 목록.
//==============================================================================
import { VAsset } from "../core/asset.js";


//==============================================================================
// 데이터 애셋.
//==============================================================================
export class VJsonAsset extends VAsset
{
	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================
	/** @type { Object } */ data;

	//==============================================================================
	// 생성.
	//==============================================================================
	constructor() {
		super();
		this.data = null;
	}

	//==============================================================================
	// 비동기 애셋 로드.
	//==============================================================================
	/**
	 * @override
	 * @param { string } assetPath 
	 */
	async load(assetPath) {
		await super.load(assetPath);

		// 이미 로드 된 상태라면.
		if (super.isLoaded) {
			return Promise.resolve();
		}
		else {
			try {
				// 로드.
				const response = await fetch(assetPath);
				this.data = await response.json();
				super.isLoaded = true;
			}
			catch (error) {
				// 예외.
				console.error(`Error loading json: ${super.assetPath}`, error);
				throw error;
			}
		}
	}

	//==============================================================================
	// 애셋 언로드.
	//==============================================================================
	/**
	 * @override
	 * @method
	 */
	unload() {
		super.unload();
		this.data = null;
	}
}