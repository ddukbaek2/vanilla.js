//==============================================================================
// 포함 모듈 목록.
//==============================================================================
import { VTextAsset } from "../resource/textasset.js";


//==============================================================================
// JSON 데이터 애셋.
//==============================================================================
export class VJsonAsset extends VTextAsset
{
	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================
	/** @type { Object | null } */ data;

	//==============================================================================
	// 생성.
	//==============================================================================
	constructor() {
		super();
		this.data = null;
	}

	//==============================================================================
	// 비동기 애셋 로드.
	//==============================================================================
	/**
	 * @override
	 * @param { string } assetPath 
	 */
	async load(assetPath) {
		// 이미 로드 된 상태라면.
		if (super.isLoaded) {
			return Promise.resolve();
		}

		// 로드.
		await super.load(assetPath);

		if (super.isLoaded) {
			try {
				this.data = JSON.parse(this.text);
			}
			catch (error) {
				console.error(`Error loading json: ${assetPath}`, error);
				super.isLoaded = false;
			}
		}
	}

	//==============================================================================
	// 애셋 언로드.
	//==============================================================================
	/**
	 * @override
	 * @method
	 */
	unload() {
		super.unload();
		this.data = null;
	}
}