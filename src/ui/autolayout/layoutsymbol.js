//==============================================================================
// 포함 모듈 목록.
//==============================================================================
const System = globalThis;
import { LayoutSymbolType } from "./layoutsymboltype.js";


//==============================================================================
// 솔버 내부 심볼. (외부 노출 X)
// - 행 / 열 식별자로 사용된다.
// - id 는 전역 시퀀스로 부여되어 Map 키 역할을 동시에 수행.
//==============================================================================
export class LayoutSymbol {
	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================
	/** @private @type { number } */ #id;
	/** @private @type { number } */ #type;

	//==============================================================================
	// 시퀀스 생성기.
	//==============================================================================
	/** @private @type { number } */
	static #nextId = 1;

	//==============================================================================
	// 생성. type 은 LayoutSymbolType 값 중 하나.
	//==============================================================================
	/**
	 * @constructor
	 * @param { number } type
	 */
	constructor(type) {
		this.#id = LayoutSymbol.#nextId;
		LayoutSymbol.#nextId += 1;
		this.#type = (typeof type === "number") ? type : LayoutSymbolType.invalid;
	}

	//==============================================================================
	// 무효 심볼 팩토리.
	//==============================================================================
	/**
	 * @returns { LayoutSymbol }
	 */
	static invalid() {
		const symbol = new LayoutSymbol(LayoutSymbolType.invalid);
		return symbol;
	}

	//==============================================================================
	// 식별자 반환.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getId() {
		return this.#id;
	}

	//==============================================================================
	// 타입 반환.
	//==============================================================================
	/**
	 * @returns { number }
	 */
	getType() {
		return this.#type;
	}

	//==============================================================================
	// 타입 변경. (행 swap 등 내부 연산 중 일시적으로 사용)
	//==============================================================================
	/**
	 * @param { number } type
	 */
	setType(type) {
		this.#type = type;
	}

	//==============================================================================
	// 무효 심볼 여부.
	//==============================================================================
	/**
	 * @returns { boolean }
	 */
	isInvalid() {
		return this.getType() === LayoutSymbolType.invalid;
	}
}
