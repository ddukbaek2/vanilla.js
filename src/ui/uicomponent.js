const System = globalThis;
import { Component } from "../core/component.js";
import { Engine } from "../core/engine.js";


//==============================================================================
// UI 컴포넌트.
// - AnchoredWorldNode에 부착되는 컴포넌트의 기반 클래스.
//==============================================================================
export class UIComponent extends Component {
	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================
	/** @private @type { Engine } */ #engine;

	//==============================================================================
	// 생성.
	//==============================================================================
	/**
	 * @constructor
	 */
	constructor() {
		super();
		this.setComponentType("UI");
		this.#engine = null;
	}

	//==============================================================================
	// 엔진 설정.
	//==============================================================================
	/**
	 * @param { Enigne } engine
	 */
	setEngine(engine) {
		this.#engine = engine;
	}

	//==============================================================================
	// 엔진 반환.
	//==============================================================================
	/**
	 * @returns { Enigne | null }
	 */
	getEngine() {
		return this.#engine;
	}

}
