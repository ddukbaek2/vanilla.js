//==============================================================================
// 포함 모듈 목록.
//==============================================================================
import { Renderer } from "../core/renderer.js";
import { UINode } from "./uinode.js";


//==============================================================================
// UI 이미지.
//==============================================================================
export class UIImage extends UINode {
	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================
	/** @private @type { HTMLImageElement } */ #image;
	/** @private @type { Rect } */ #slices;
	/** @private @type { Rect } */ #edges;

	//==============================================================================
	// 생성.
	//==============================================================================
	constructor() {
		super();
		this.#image = null;
		this.#edges = Rect.zero();
		this.#slices = Rect.zero();
	}

	//==============================================================================
	// 갱신.
	//==============================================================================
	/**
	 * @override
	 * @param { number } timeDelta 
	 */
	update(timeDelta) {
		super.update(timeDelta);
	}

	//==============================================================================
	// 출력.
	//==============================================================================
	/**
	 * @override
	 * @param { Renderer } renderer 
	 */
	draw(renderer) {
		super.draw(renderer);
	}

	//==============================================================================
	// 이미지 나인패치 설정.
	//==============================================================================
	/**
	 * @param { Rect } edges 
	 */
	setEdges(edges) {
		this.#edges = edges;
	}

	//==============================================================================
	// 이미지 나인패치 반환.
	//==============================================================================
	/**
	 * @returns { Rect }
	 */
	getEdges() {
		return this.#edges;
	}
}