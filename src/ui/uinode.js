//==============================================================================
// 포함 모듈 목록.
//==============================================================================
import { VVector2 } from "../base/vector2.js";
import { VRenderer } from "../core/renderer.js";
import { VNode } from "../core/node.js";


//==============================================================================
// UI 기반 뷰.
//==============================================================================
export class UINode extends VNode {
	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================
	/** @private @type { Vector2 } */ #anchor;

	//==============================================================================
	// 생성.
	//==============================================================================
	constructor() {
		super();
		this.#anchor = VVector2.zero();
	}

	//==============================================================================
	// 갱신.
	//==============================================================================
	/**
	 * @override
	 * @param { number } timeDelta 
	 */
	update(timeDelta) {
		super.update(timeDelta);
	}

	//==============================================================================
	// 출력.
	//==============================================================================
	/**
	 * @override
	 * @param { VRenderer } renderer 
	 */
	draw(renderer) {
		super.draw(renderer);
	}

	//==============================================================================
	// 앵커 설정.
	//==============================================================================
	/**
	 * @param { VVector2 } anchor 
	 */
	setAnchor(anchor) {
		this.#anchor = anchor;
	}
	
	//==============================================================================
	// 앵커 반환.
	//==============================================================================
	/**
	 * @returns { VVector2 }
	 */
	getAnchor() {
		return this.#anchor;
	}
}