//==============================================================================
// 포함 모듈 목록.
//==============================================================================
import { Vector2 } from "../base/vector2.js";
import { Renderer } from "../core/renderer.js";
import { Node } from "../core/node.js";


//==============================================================================
// UI 기반 뷰.
//==============================================================================
export class UINode extends Node {
	//==============================================================================
	// 멤버 변수 목록.
	//==============================================================================
	/** @private @type { Vector2 } */ #anchorMin;
	/** @private @type { Vector2 } */ #anchorMax;

	//==============================================================================
	// 생성.
	//==============================================================================
	constructor() {
		super();
		this.#anchorMin = Vector2.zero();
		this.#anchorMax = Vector2.zero();
	}

	//==============================================================================
	// 갱신.
	//==============================================================================
	/**
	 * @override
	 * @param { number } timeDelta 
	 */
	tick(timeDelta) {
		super.tick(timeDelta);
	}

	//==============================================================================
	// 출력 상태 시작.
	//==============================================================================
	/**
	 * @override
	 * @param { Renderer } renderer 
	 */
	pushMatrix(renderer) {
		super.pushMatrix(renderer);
	}

	//==============================================================================
	// 출력.
	//==============================================================================
	/**
	 * @override
	 * @param { Renderer } renderer 
	 */
	draw(renderer) {
		super.draw(renderer);
	}

	//==============================================================================
	// 출력 상태 종료.
	//==============================================================================
	/**
	 * @override
	 * @param { Renderer } renderer 
	 */
	popMatrix(renderer) {
		super.popMatrix(renderer);
	}

	//==============================================================================
	// 앵커 설정.
	//==============================================================================
	/**
	 * @param { Vector2 } anchorMin 
	 */
	setAnchorMin(anchorMin) {
		this.#anchorMin = anchorMin;
	}

	//==============================================================================
	// 앵커 설정.
	//==============================================================================
	/**
	 * @param { Vector2 } anchorMax 
	 */
	setAnchorMax(anchorMax) {
		this.#anchorMax = anchorMax;
	}

	//==============================================================================
	// 앵커 반환.
	//==============================================================================
	/**
	 * @returns { Vector2 }
	 */
	getAnchorMin() {
		return this.#anchorMin;
	}

	//==============================================================================
	// 앵커 반환.
	//==============================================================================
	/**
	 * @returns { Vector2 }
	 */
	getAnchorMax() {
		return this.#anchorMax;
	}
}